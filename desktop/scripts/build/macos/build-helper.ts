/**
 * Compile the macOS privileged helper (SMAppService LaunchDaemon + control
 * tool) from the Swift sources in `native/` into universal Mach-O binaries that
 * electron-builder bundles into the `.app` via `mac.extraFiles`.
 *
 * Runs on the mac CI runner only — `swiftc` ships with Xcode Command Line Tools
 * (already present alongside `xcrun`/`codesign`/`notarytool`); no full Xcode or
 * `.xcodeproj` is needed. We cross-compile each arch with
 * `swiftc -target <arch>-apple-macos13.0` and `lipo` them into one universal
 * binary so the same artifact ships in both the x64 and arm64 `.app`s.
 *
 * Outputs (referenced verbatim by electron-builder.config.ts mac.extraFiles):
 *   native/build/com.nvidia.nvpair.helper   (the root daemon)
 *   native/build/nvpair-helper-ctl          (the user-context control tool)
 */

import { execFileSync, spawnSync } from 'node:child_process'
import { chmodSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { currentPlatform } from '@/shared/utils/platform'

const ROOT = path.resolve(__dirname, '..', '..', '..')
const NATIVE_DIR = path.join(ROOT, 'native')
const BUILD_DIR = path.join(NATIVE_DIR, 'build')
const SHARED_DIR = path.join(NATIVE_DIR, 'Shared')
const DAEMON_DIR = path.join(NATIVE_DIR, 'PrivilegedHelper')
const CTL_DIR = path.join(NATIVE_DIR, 'HelperControl')

const DAEMON_OUTPUT = 'com.nvidia.nvpair.helper'
const CTL_OUTPUT = 'nvpair-helper-ctl'
const ARCHS = ['arm64', 'x86_64'] as const
const DEPLOYMENT_TARGET = '13.0'

function findSwiftc(): string {
    const result = spawnSync('xcrun', ['--find', 'swiftc'], { encoding: 'utf8' })
    if (result.status !== 0 || !result.stdout.trim()) {
        throw new Error(
            'swiftc not found. Install Xcode Command Line Tools (xcode-select --install) ' +
                'before building the macOS privileged helper.'
        )
    }
    return result.stdout.trim()
}

/**
 * swiftc is invoked by its resolved toolchain path (not via `xcrun swiftc`), so
 * the environment carries no `SDKROOT`. Without it swiftc cannot locate the
 * macOS SDK and fails with "unable to load standard library for target ...". We
 * resolve the SDK path explicitly and pass it with `-sdk` so the build does not
 * depend on inherited toolchain env.
 */
function findMacosSdkPath(): string {
    const result = spawnSync('xcrun', ['--sdk', 'macosx', '--show-sdk-path'], { encoding: 'utf8' })
    if (result.status !== 0 || !result.stdout.trim()) {
        throw new Error(
            'macOS SDK not found. Ensure Xcode (or the Command Line Tools) is selected ' +
                'via `xcode-select` before building the macOS privileged helper.'
        )
    }
    return result.stdout.trim()
}

function appVersion(): string {
    const parsed: { version?: string } = JSON.parse(
        readFileSync(path.join(ROOT, 'package.json'), 'utf8')
    )
    if (!parsed.version) throw new Error('package.json is missing "version"')
    return parsed.version
}

/**
 * The helper version is stamped to equal the app version so the runtime can
 * detect a stale helper and reinstall it (version-aware reinstall in Phase 4).
 */
function writeVersionSource(version: string): string {
    const file = path.join(BUILD_DIR, 'HelperVersion.swift')
    writeFileSync(
        file,
        '// Generated by scripts/build/macos/build-helper.ts — do not edit.\n' +
            'enum HelperVersionInfo {\n' +
            `    static let version = "${version}"\n` +
            '}\n',
        'utf8'
    )
    return file
}

function swiftSources(dir: string): string[] {
    return readdirSync(dir)
        .filter(name => name.endsWith('.swift'))
        .map(name => path.join(dir, name))
        .sort()
}

function buildUniversal(
    swiftc: string,
    sdkPath: string,
    outputName: string,
    sources: string[],
    frameworks: string[]
): void {
    const archBinaries: string[] = []
    for (const arch of ARCHS) {
        const archDir = path.join(BUILD_DIR, arch)
        mkdirSync(archDir, { recursive: true })
        const archOut = path.join(archDir, outputName)
        const frameworkArgs = frameworks.flatMap(name => ['-framework', name])
        execFileSync(
            swiftc,
            [
                '-O',
                '-sdk',
                sdkPath,
                '-target',
                `${arch}-apple-macos${DEPLOYMENT_TARGET}`,
                ...frameworkArgs,
                '-o',
                archOut,
                ...sources
            ],
            { stdio: 'inherit' }
        )
        archBinaries.push(archOut)
    }
    const universal = path.join(BUILD_DIR, outputName)
    execFileSync('lipo', ['-create', ...archBinaries, '-output', universal], { stdio: 'inherit' })
    chmodSync(universal, 0o755)
    console.log(`[build-helper] built universal ${outputName}`)
}

function main(): void {
    if (currentPlatform() !== 'darwin') {
        throw new Error('build-helper.ts only runs on macOS (it needs swiftc).')
    }
    const swiftc = findSwiftc()
    const sdkPath = findMacosSdkPath()
    rmSync(BUILD_DIR, { recursive: true, force: true })
    mkdirSync(BUILD_DIR, { recursive: true })

    const version = appVersion()
    const versionSource = writeVersionSource(version)
    const shared = swiftSources(SHARED_DIR)

    buildUniversal(
        swiftc,
        sdkPath,
        DAEMON_OUTPUT,
        [...shared, versionSource, ...swiftSources(DAEMON_DIR)],
        ['Foundation', 'Security']
    )
    buildUniversal(
        swiftc,
        sdkPath,
        CTL_OUTPUT,
        [...shared, versionSource, ...swiftSources(CTL_DIR)],
        ['Foundation', 'ServiceManagement']
    )

    console.log(`[build-helper] helper binaries ready in ${BUILD_DIR} (v${version})`)
}

main()
